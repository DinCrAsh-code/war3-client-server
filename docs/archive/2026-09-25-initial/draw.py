OUT = Path(__file__).resolve().parent
FONT = "C:/Windows/Fonts/calibri.ttf"
FONTB = "C:/Windows/Fonts/calibrib.ttf"
S = 2  # supersampling


def f(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONTB if bold else FONT, size * S)


def box(d: ImageDraw.ImageDraw, xy, fill, outline, title, lines, tf=22, lf=17, radius=14, title_color="black", text_color="#222"):
    x0, y0, x1, y1 = [v * S for v in xy]
    d.rounded_rectangle((x0, y0, x1, y1), radius=radius * S, fill=fill, outline=outline, width=3 * S)
    d.text((x0 + 14 * S, y0 + 10 * S), title, font=f(tf, True), fill=title_color)
    y = y0 + (10 + tf + 8) * S
    for ln in lines:
        d.text((x0 + 14 * S, y), ln, font=f(lf), fill=text_color)
        y += (lf + 5) * S


def arrow(d, p0, p1, color="#333", width=4, label=None, lf=16, label_dy=-22, dash=False):
    x0, y0 = p0[0] * S, p0[1] * S
    x1, y1 = p1[0] * S, p1[1] * S
    if dash:
        import math
        L = math.hypot(x1 - x0, y1 - y0)
        n = int(L // (14 * S))
        for i in range(0, n, 2):
            a = i / n
            b = min((i + 1) / n, 1)
            d.line((x0 + (x1 - x0) * a, y0 + (y1 - y0) * a, x0 + (x1 - x0) * b, y0 + (y1 - y0) * b), fill=color, width=width * S)
    else:
        d.line((x0, y0, x1, y1), fill=color, width=width * S)
    # head
    import math
    ang = math.atan2(y1 - y0, x1 - x0)
    hl = 16 * S
    for da in (math.pi / 7, -math.pi / 7):
        d.line((x1, y1, x1 - hl * math.cos(ang - da), y1 - hl * math.sin(ang - da)), fill=color, width=width * S)
    if label:
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        w = d.textlength(label, font=f(lf))
        d.rectangle((mx - w / 2 - 6 * S, my + label_dy * S - 4 * S, mx + w / 2 + 6 * S, my + (label_dy + lf + 4) * S), fill="white")
        d.text((mx - w / 2, my + label_dy * S), label, font=f(lf), fill=color)


